// Regenerates lib/nycOutline.ts from NYC Open Data "Borough Boundaries" (gthc-hcne).
// Usage (from frontend/): node scripts/build-nyc-outline.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = "https://data.cityofnewyork.us/resource/gthc-hcne.geojson";
const OUT = fileURLToPath(new URL("../lib/nycOutline.ts", import.meta.url));
const WIDTH = 560;
const TOLERANCE = 0.9;
const MIN_AREA = 12;
const METERS_PER_DEG_LAT = 111_320;
const K = Math.cos((40.7 * Math.PI) / 180);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} -> HTTP ${res.status}`);
const geo = await res.json();

const rings = [];
for (const f of geo.features) {
  const name = f.properties.boroname;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) rings.push({ name, pts: poly[0] });
}

let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const { pts } of rings) {
  for (const [lon, lat] of pts) {
    const x = lon * K, y = -lat;
    minX = Math.min(minX, x); maxX = Math.max(maxX, x);
    minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  }
}
const scale = WIDTH / (maxX - minX);
const height = Math.ceil((maxY - minY) * scale);
const project = ([lon, lat]) => [(lon * K - minX) * scale, (-lat - minY) * scale];

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay;
    const len = Math.hypot(dx, dy);
    let worst = -1, idx = -1;
    for (let i = a + 1; i < b; i++) {
      // Closed rings start and end on the same point, so the first split measures distance to that point.
      const d = len === 0
        ? Math.hypot(pts[i][0] - ax, pts[i][1] - ay)
        : Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > worst) { worst = d; idx = i; }
    }
    if (worst > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const area = (pts) => {
  let s = 0;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) s += (pts[j][0] + pts[i][0]) * (pts[j][1] - pts[i][1]);
  return Math.abs(s / 2);
};

const byBorough = new Map();
let points = 0;
for (const { name, pts } of rings) {
  const projected = simplify(pts.map(project), TOLERANCE);
  if (projected.length < 4 || area(projected) < MIN_AREA) continue;
  points += projected.length;
  const d = "M" + projected.slice(0, -1).map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z";
  byBorough.set(name, (byBorough.get(name) ?? "") + d);
}

const boroughs = [...byBorough.entries()].map(([name, d]) => ({ name, d }));
const file = `// Generated by scripts/build-nyc-outline.mjs from NYC Open Data Borough Boundaries (gthc-hcne).
// Do not edit by hand.

export const NYC_OUTLINE_WIDTH = ${WIDTH};
export const NYC_OUTLINE_HEIGHT = ${height};

export const NYC_BOROUGHS: { name: string; d: string }[] = ${JSON.stringify(boroughs, null, 2)};

const K = ${K};
const MIN_X = ${minX};
const MIN_Y = ${minY};
const SCALE = ${scale};

export function projectLngLat(lng: number, lat: number): [number, number] {
  return [(lng * K - MIN_X) * SCALE, (-lat - MIN_Y) * SCALE];
}

export function milesToOutlineUnits(miles: number): number {
  return ((miles * 1609.344) / ${METERS_PER_DEG_LAT}) * SCALE;
}
`;
writeFileSync(OUT, file);
console.log(`wrote ${OUT}: ${boroughs.length} boroughs, ${points} points, ${file.length} bytes, ${WIDTH}x${height}`);
